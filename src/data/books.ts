/**
 * The book catalogue.
 *
 * Generated from the Amazon.com / Amazon.co.uk export sheets. The `category` is
 * taken from the genre column of the Amazon.com sheet. All titles are
 * KDP expanded-distribution books that share ONE ASIN across every Amazon
 * marketplace, so `defaultAsin` is the same ASIN used for US, UK, DE, FR, and
 * the rest — the /go/[slug] route just swaps the domain to the visitor's store.
 *
 * To add a book: copy a block, fill in `title` (clean, shown on cards),
 * `fullTitle` (the long Amazon title — used for SEO), a short `blurb`, the
 * `category` + `ages` (used by the browse filters), the ASIN, and set
 * `defaultAsin` to the same ASIN. Covers auto-pull from Amazon by ASIN; to
 * self-host instead, set `cover: "/covers/<slug>.jpg"`.
 *
 * `rating` is a SNAPSHOT of the Amazon.com star rating (it changes over time).
 * Refresh it any time with: `python3 scripts/fetch-ratings.py`. Books with no
 * Amazon reviews yet simply have no `rating` and show no stars.
 */

import type { MarketplaceCode } from "@/data/marketplaces";

export type Book = {
  /** URL-safe id — becomes /book/<slug> and /go/<slug>. */
  slug: string;
  /** Clean, short title shown on cards and as the page H1. */
  title: string;
  /** Full keyword-rich Amazon title — used for SEO/meta. Optional. */
  fullTitle?: string;
  subtitle?: string;
  author: string;
  /** Short, card-sized hook. */
  blurb: string;
  /** Theme used by the browse filters (e.g. "Sports", "Travel"). */
  category: string;
  /** Age bucket used by the browse filters (e.g. "Ages 4-8"). */
  ages: string;
  /** Optional star rating for social proof (e.g. 4.6). Not shown on the site. */
  rating?: number;
  /** Optional "What's inside" chips on the book page. Omit to hide the block. */
  features?: string[];
  /** Optional explicit cover. Omit to auto-derive from the ASIN. */
  cover?: string;
  /** Optional ASIN to pull the Amazon cover from (use a PRINT ASIN). */
  coverAsin?: string;
  /** Per-marketplace ASIN. Here every book shares one ASIN across stores. */
  asins: Partial<Record<MarketplaceCode, string>>;
  /** Fallback ASIN used for any marketplace not listed above. */
  defaultAsin: string;
};

